#!/usr/bin/env node
// T1.1.5 - generates the typed client from openapi/v1.json (the platform's published CLI contract, T1.2.5), pinned by
// sha256 in contract.lock.json. The output is NEVER hand-edited: `--check` regenerates in memory and fails on any
// difference (the CI diff check), so a changed contract without regeneration, or an edited client, fails the build.
import { createHash } from 'node:crypto';
import { realpathSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SPEC = `${ROOT}openapi/v1.json`;
const LOCK = `${ROOT}contract.lock.json`;
const OUT = `${ROOT}src/index.ts`;
const METHODS = ['get', 'put', 'post', 'delete', 'patch'];

export async function generate() {
  const text = await readFile(SPEC, 'utf8');
  const spec = JSON.parse(text);
  const sha256 = createHash('sha256').update(text).digest('hex');
  const lock = `${JSON.stringify({ file: 'openapi/v1.json', sha256, contractVersion: spec.info.version }, null, 2)}\n`;
  const types = astToString(await openapiTS(spec, { alphabetize: true }));
  const operations = [];
  for (const [path, item] of Object.entries(spec.paths).sort(([a], [b]) => a.localeCompare(b))) {
    for (const method of METHODS) {
      const op = item[method];
      if (op === undefined) continue;
      operations.push({
        operationId: op.operationId ?? `${method} ${path}`,
        method: method.toUpperCase(),
        path,
        scope: op['x-cli-scope'] ?? null,
      });
    }
  }
  const index = [
    '// GENERATED by scripts/generate.mjs from openapi/v1.json - DO NOT EDIT (CI fails on any hand edit).',
    `// contract ${spec.info.version}, sha256 ${sha256}`,
    types.trimEnd(),
    '',
    `export const CONTRACT_SHA256 = '${sha256}';`,
    `export const CONTRACT_VERSION = '${spec.info.version}';`,
    '',
    'export interface Operation {',
    '  readonly operationId: string;',
    "  readonly method: 'GET' | 'PUT' | 'POST' | 'DELETE' | 'PATCH';",
    '  readonly path: string;',
    '  readonly scope: string | null;',
    '}',
    '',
    `export const OPERATIONS: readonly Operation[] = ${JSON.stringify(operations, null, 2)};`,
    '',
    '/** The contract\'s named JSON Schemas (components.schemas), for runtime validation and generators (T2.1.5). */',
    `export const COMPONENT_SCHEMAS: Readonly<Record<string, unknown>> = ${JSON.stringify(spec.components?.schemas ?? {}, null, 2)};`,
    '',
  ].join('\n');
  return { lock, index };
}

const check = process.argv.includes('--check');
// Real paths on both sides: a symlinked temp dir (macOS /var -> /private/var) must still count as "run directly".
const isMain = process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
if (isMain) {
  const { lock, index } = await generate();
  if (check) {
    const [onDiskLock, onDiskIndex] = await Promise.all([readFile(LOCK, 'utf8').catch(() => ''), readFile(OUT, 'utf8').catch(() => '')]);
    const drift = [];
    if (onDiskLock !== lock) drift.push('contract.lock.json');
    if (onDiskIndex !== index) drift.push('src/index.ts');
    if (drift.length > 0) {
      process.stderr.write(`Generated client drift: ${drift.join(', ')} differ from openapi/v1.json. Run \`pnpm --filter @revition/api-client generate\`.\n`);
      process.exit(1);
    }
    process.stdout.write('generated client matches openapi/v1.json\n');
  } else {
    await writeFile(LOCK, lock);
    await writeFile(OUT, index);
    process.stdout.write('generated src/index.ts and contract.lock.json\n');
  }
}
